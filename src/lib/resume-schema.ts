import { z } from "zod";

/**
 * Canonical Resume Variant contracts — browser-safe (no Prisma/Node deps).
 *
 * A Resume Variant is a deterministic SNAPSHOT of selected canonical
 * Master Career Profile data composed for one purpose (target role,
 * target country, template). It never writes back to the MCP.
 */

/* ------------------------------------------------------------------ */
/* Template registry — identity contract only; rendering comes later.  */
/* ------------------------------------------------------------------ */

