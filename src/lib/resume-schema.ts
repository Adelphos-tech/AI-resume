/* ------------------------------------------------------------------ */
/* Section order — deterministic fixed order for V1.                   */
/* ------------------------------------------------------------------ */

export const RESUME_SECTION_KEYS = [
  "summary",
  "experience",
  "skills",
  "education",
  "projects",
  "certifications",
  "languages",
] as const;

export type ResumeSectionKey = (typeof RESUME_SECTION_KEYS)[number];

export const DEFAULT_RESUME_SECTION_ORDER: ResumeSectionKey[] = [
  ...RESUME_SECTION_KEYS,
];

const sectionOrder = z
  .array(z.enum(RESUME_SECTION_KEYS))
  .length(RESUME_SECTION_KEYS.length)
  .refine((order) => new Set(order).size === RESUME_SECTION_KEYS.length, {
    message: "sectionOrder must contain each supported section once",
  });

/* ------------------------------------------------------------------ */
/* Shared primitives                                                   */
/* ------------------------------------------------------------------ */

const reqString = (max: number) => z.string().trim().min(1).max(max);

const optString = (max: number) =>
  z
    .string()
    .trim()
    .max(max)
    .nullish()
    .transform((v) => (v ? v : null));

const isHttpUrl = (v: string) => {
  try {
    const u = new URL(v);
    return u.protocol === "http:" || u.protocol === "https:";
  } catch {
    return false;
  }
};

const optUrl = z
  .string()
  .trim()
  .max(2048)
  .nullish()
  .transform((v) => (v ? v : null))
  .refine((v) => v === null || isHttpUrl(v));

const optDate = z
  .string()
  .trim()
  .nullish()
  .transform((v) => (v ? v : null))
  .refine((v) => v === null || /^\d{4}(-\d{2})?$/.test(v));

/** Canonical profile-entry UUID a resume item was composed from. */
const sourceId = z.uuid();

/**
 * Deterministic renderable-block identifier generated by the server
 * composer, e.g. `basics:summary`, `work:<uuid>:highlight:2`.
 * Bounded, lowercase-segmented, no HTML-capable characters.
 */
const blockId = z
  .string()
  .max(200)
  .regex(/^[a-z]+(:[a-zA-Z0-9-]+)*$/, "Invalid block id");

const textBlock = z.strictObject({
  id: blockId,
  text: z.string().trim().min(1).max(5000),
});

const keywordBlock = z.strictObject({
  id: blockId,
  text: z.string().trim().min(1).max(100),
});

/* ------------------------------------------------------------------ */
/* ResumeData — content destined for rendering                          */
/* ------------------------------------------------------------------ */

const resumeBasics = z.strictObject({
  fullName: reqString(200),
  headline: optString(300),
  email: z.email().nullable().default(null),
  phone: optString(50),
  location: optString(200),
  links: z
    .array(
      z.strictObject({
        label: reqString(100),
        url: optUrl,
      }),
    )
    .max(20),
});

const resumeExperience = z.strictObject({
  sourceId,
  blockId,
  company: reqString(300),
  position: reqString(300),
  location: optString(200),
  employmentType: optString(100),
  startDate: optDate,
  endDate: optDate,
  isCurrent: z.boolean(),
  summary: textBlock.nullable().default(null),
  highlights: z.array(textBlock).max(30),
});

const resumeEducation = z.strictObject({
  sourceId,
  blockId,
  institution: reqString(300),
  degree: optString(200),
  fieldOfStudy: optString(200),
  location: optString(200),
  startDate: optDate,
  endDate: optDate,
  grade: optString(100),
  highlights: z.array(textBlock).max(30),
});

const resumeSkillGroup = z.strictObject({
  sourceId,
  blockId,
  name: reqString(200),
  keywords: z.array(keywordBlock).max(50),
});

const resumeProject = z.strictObject({
  sourceId,
  blockId,
  name: reqString(300),
  description: textBlock.nullable().default(null),
  url: optUrl,
  startDate: optDate,
  endDate: optDate,
  highlights: z.array(textBlock).max(30),
});

const resumeCertification = z.strictObject({
  sourceId,
  blockId,
  name: reqString(300),
  issuer: optString(300),
  date: optDate,
  expiryDate: optDate,
  credentialId: optString(200),
  url: optUrl,
});

const resumeLanguage = z.strictObject({
  sourceId,
  blockId,
  language: reqString(200),
  fluency: optString(100),
});

export const resumeDataSchema = z.strictObject({
  basics: resumeBasics,
  summary: textBlock.nullable().default(null),
  experience: z.array(resumeExperience).max(30),
  education: z.array(resumeEducation).max(20),
  skills: z.array(resumeSkillGroup).max(30),
  projects: z.array(resumeProject).max(30),
  certifications: z.array(resumeCertification).max(30),
  languages: z.array(resumeLanguage).max(20),
  sectionOrder,
});

export type ResumeData = z.infer<typeof resumeDataSchema>;

/* ------------------------------------------------------------------ */
/* Variant creation config — the ONLY input the browser may send.       */
/* ------------------------------------------------------------------ */

export const createResumeVariantConfigSchema = z.strictObject({
  name: reqString(200),
  targetRole: reqString(200),
  targetCountry: reqString(100),
  templateKey: z.enum(RESUME_TEMPLATE_KEYS),
});

export type CreateResumeVariantConfig = z.infer<
  typeof createResumeVariantConfigSchema
>;
