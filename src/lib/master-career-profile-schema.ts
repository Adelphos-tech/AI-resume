import { z } from "zod";

/**
 * Canonical Master Career Profile document contract (V1).
 *
 * Browser-safe: no server-only, Prisma, filesystem, or AI imports.
 * Consumed by server boundaries today; later by the admin editor,
 * AI structured-output integration, and resume renderers.
 */

export const MASTER_CAREER_PROFILE_SCHEMA_VERSION = 1;

// Serialized canonical JSON size ceiling — a legitimate profile is far
// below this; it exists to stop pathological payloads.
export const MAX_PROFILE_JSON_BYTES = 500 * 1024;

// --- Shared primitives -----------------------------------------------------

const reqString = (max: number) => z.string().trim().min(1).max(max);

// Optional free text: trims, then normalizes blank/absent to null so the
// stored document never carries meaningless empty strings.
const optString = (max: number) =>
  z
    .string()
    .trim()
    .max(max)
    .nullish()
    .transform((v) => (v ? v : null));

// Canonical career dates are partial: YYYY or YYYY-MM only. Never fabricate
// days/months; use isCurrent instead of a "Present" string.
export const careerPartialDateSchema = z
  .string()
  .trim()
  .regex(/^\d{4}$|^\d{4}-(0[1-9]|1[0-2])$/);

const optDate = z
  .string()
  .trim()
  .nullish()
  .transform((v) => (v ? v : null))
  .refine((v) => v === null || careerPartialDateSchema.safeParse(v).success);

const isHttpUrl = (v: string) => {
  try {
    const u = new URL(v);
    return u.protocol === "http:" || u.protocol === "https:";
  } catch {
    return false;
  }
};

const urlSchema = z.string().trim().max(2048).refine(isHttpUrl);

const optUrl = z
  .string()
  .trim()
  .max(2048)
  .nullish()
  .transform((v) => (v ? v : null))
  .refine((v) => v === null || isHttpUrl(v));

const optEmail = z
  .string()
  .trim()
  .max(320)
  .nullish()
  .transform((v) => (v ? v : null))
  .refine((v) => v === null || z.email().safeParse(v).success);

// Profile-entry ids are opaque UUIDs generated by crypto.randomUUID() when
// entries are created — deliberately not Prisma/database identity.
const entryId = z.uuid();

// Trims items, drops empties, deterministic exact-duplicate removal.
const stringList = (itemMax: number) =>
  z
    .array(z.string().trim().max(itemMax))
    .transform((items) => [...new Set(items.filter((i) => i.length > 0))]);

const MAX_WORK = 30;
const MAX_EDUCATION = 20;
const MAX_SKILL_GROUPS = 30;
const MAX_PROJECTS = 30;
const MAX_CERTIFICATIONS = 30;
const MAX_LANGUAGES = 20;
const MAX_HIGHLIGHTS = 30;
const MAX_KEYWORDS = 50;
const MAX_LINKS = 20;
const MAX_PROFESSIONAL_CATEGORIES = 20;
const MAX_GENRES = 20;

// --- Sections ----------------------------------------------------------------

export const masterCareerProfileBasicsSchema = z.strictObject({
  // Nullable: a stored draft may be empty; resume-ready requires it.
  fullName: optString(200),
  headline: optString(300),
  summary: optString(5000),
  email: optEmail,
  phone: optString(50),
  location: optString(200),
  links: z
    .array(
      z.strictObject({
        label: reqString(100),
        url: urlSchema,
      }),
    )
    .max(MAX_LINKS)
    .transform((links) => {
      const seen = new Set<string>();
      return links.filter((l) =>
        seen.has(l.url) ? false : (seen.add(l.url), true),
      );
    }),
  // Creative/entertainment professional identity — canonical career metadata
  // reusable by Resume, Career Card, and Career Site.
  // Optional for backward compatibility with stored profiles created before
  // these fields existed.
  professionalCategories: stringList(100)
    .pipe(z.array(z.string()).max(MAX_PROFESSIONAL_CATEGORIES))
    .optional(),
  genres: stringList(100).pipe(z.array(z.string()).max(MAX_GENRES)).optional(),
  portfolioUrl: optUrl.optional(),
  showreelUrl: optUrl.optional(),
});

/**
 * Conservative chronology check for partial career dates (YYYY or YYYY-MM).
 * Rejects only what is provably contradictory — a missing month preserves
 * uncertainty rather than fabricating precision:
 *
 *   different years:            reject if end year < start year
 *   same year, both months:     reject if end month < start month
 *   same year, missing month:   accept (unknown ordering)
 */
export function isValidCareerDateRange(
  startDate: string | null,
  endDate: string | null,
): boolean {
  if (startDate === null || endDate === null) return true;
  const [startYear, startMonth] = startDate.split("-");
  const [endYear, endMonth] = endDate.split("-");
  if (endYear !== startYear) return endYear > startYear;
  if (startMonth !== undefined && endMonth !== undefined) {
    return endMonth >= startMonth;
  }
  return true;
}

export const masterCareerProfileWorkEntrySchema = z
  .strictObject({
    id: entryId,
    company: reqString(300),
    position: reqString(300),
    location: optString(200),
    employmentType: optString(100),
    startDate: optDate,
    endDate: optDate,
    isCurrent: z.boolean(),
    summary: optString(5000),
    highlights: stringList(1000).pipe(z.array(z.string()).max(MAX_HIGHLIGHTS)),
  })
  .refine((w) => !(w.isCurrent && w.endDate !== null), {
    message: "endDate must be null when isCurrent is true",
  })
  .refine((w) => isValidCareerDateRange(w.startDate, w.endDate), {
    message: "endDate cannot be before startDate",
  });

export const masterCareerProfileEducationEntrySchema = z
  .strictObject({
    id: entryId,
    institution: reqString(300),
    degree: optString(200),
    fieldOfStudy: optString(200),
    location: optString(200),
    startDate: optDate,
    endDate: optDate,
    grade: optString(100),
    highlights: stringList(1000).pipe(z.array(z.string()).max(MAX_HIGHLIGHTS)),
  })
  .refine((e) => isValidCareerDateRange(e.startDate, e.endDate), {
    message: "endDate cannot be before startDate",
  });

export const masterCareerProfileSkillGroupSchema = z.strictObject({
  id: entryId,
  name: reqString(200),
  keywords: stringList(100).pipe(z.array(z.string()).max(MAX_KEYWORDS)),
});

export const masterCareerProfileProjectEntrySchema = z
  .strictObject({
    id: entryId,
    name: reqString(300),
    description: optString(5000),
    highlights: stringList(1000).pipe(z.array(z.string()).max(MAX_HIGHLIGHTS)),
    url: optUrl,
    startDate: optDate,
    endDate: optDate,
  })
  .refine((p) => isValidCareerDateRange(p.startDate, p.endDate), {
    message: "endDate cannot be before startDate",
  });

export const masterCareerProfileCertificationEntrySchema = z
  .strictObject({
    id: entryId,
    name: reqString(300),
    issuer: optString(300),
    date: optDate,
    expiryDate: optDate,
    credentialId: optString(200),
    url: optUrl,
  })
  .refine((c) => isValidCareerDateRange(c.date, c.expiryDate), {
    message: "expiryDate cannot be before date",
  });

export const masterCareerProfileLanguageEntrySchema = z.strictObject({
  id: entryId,
  language: reqString(100),
  fluency: optString(100),
});

// --- Canonical document --------------------------------------------------------

export const masterCareerProfileSchema = z.strictObject({
  basics: masterCareerProfileBasicsSchema,
  work: z.array(masterCareerProfileWorkEntrySchema).max(MAX_WORK),
  education: z
    .array(masterCareerProfileEducationEntrySchema)
    .max(MAX_EDUCATION),
  skills: z.array(masterCareerProfileSkillGroupSchema).max(MAX_SKILL_GROUPS),
  projects: z.array(masterCareerProfileProjectEntrySchema).max(MAX_PROJECTS),
  certifications: z
    .array(masterCareerProfileCertificationEntrySchema)
    .max(MAX_CERTIFICATIONS),
  languages: z.array(masterCareerProfileLanguageEntrySchema).max(MAX_LANGUAGES),
});

export type MasterCareerProfileData = z.infer<typeof masterCareerProfileSchema>;

/**
 * Structural minimum to generate a meaningful resume — no subjective
 * quality rules. A valid stored draft is not necessarily resume-ready.
 */
export const resumeReadyMasterCareerProfileSchema =
  masterCareerProfileSchema.refine(
    (p) =>
      p.basics.fullName !== null &&
      (p.work.length > 0 || p.education.length > 0 || p.projects.length > 0),
  );

export function createEmptyMasterCareerProfile(): MasterCareerProfileData {
  return {
    basics: {
      fullName: null,
      headline: null,
      summary: null,
      email: null,
      phone: null,
      location: null,
      links: [],
      professionalCategories: [],
      genres: [],
      portfolioUrl: null,
      showreelUrl: null,
    },
    work: [],
    education: [],
    skills: [],
    projects: [],
    certifications: [],
    languages: [],
  };
}

